export function oauthFailureCategory(error:unknown):string {
 try{if(error instanceof PlatformDenied){const reason=Object.getOwnPropertyDescriptor(error,"reason")?.value;if(typeof reason==="string"&&safeReasons.has(reason))return reason;}}catch{ /* Error objects are untrusted; never serialize them. */ }
 return "UNEXPECTED_INTERNAL_FAILURE";
}
export function logOAuthFailure(stage:"callback"|"provider_exchange",error:unknown):void {
 logger.warn({event:"platform_oauth_failure",stage,reason:oauthFailureCategory(error)},"Platform OAuth failed");
}
